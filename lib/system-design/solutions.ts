export function getReferenceSolution(
  challengeId: string,
  level: SolutionLevel = "intermediate"
): DesignGraph | null {
  const tiers = referenceSolutions[challengeId];
  if (!tiers) return null;
  const g = tiers[level];
  return g ? cloneGraph(g) : null;
}

export function hasReferenceSolution(challengeId: string): boolean {
  return Boolean(referenceSolutions[challengeId]);
}
