import type { DesignEdge, DesignGraph, DesignNode, EdgeKind } from "./types.ts";

export type SolutionLevel = "simple" | "intermediate" | "advanced";

export const SOLUTION_LEVELS: SolutionLevel[] = [
  "simple",
  "intermediate",
  "advanced",
];

export const SOLUTION_LEVEL_LABELS: Record<SolutionLevel, string> = {
  simple: "Simple",
  intermediate: "Intermediate",
  advanced: "Advanced",
};

function n(
  id: string,
  componentId: string,
  x: number,
  y: number
): DesignNode {
  return { id, componentId, position: { x, y } };
}

function e(
  source: string,
  target: string,
  kind: EdgeKind = "request"
): DesignEdge {
  return { id: `${source}->${target}`, source, target, kind };
}

function cloneGraph(g: DesignGraph): DesignGraph {
  return {
    nodes: g.nodes.map((node) => ({
      ...node,
      position: { ...node.position },
    })),
    edges: g.edges.map((edge) => ({ ...edge })),
  };
}

